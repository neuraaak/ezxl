"""Pre-commit hook: validate TOML syntax."""

# ///////////////////////////////////////////////////////////////
# IMPORTS
# ///////////////////////////////////////////////////////////////
# Standard library
import sys
import tomllib

# ///////////////////////////////////////////////////////////////

rc = 0
for path in sys.argv[1:]:
    try:
        with open(path, "rb") as f:
            tomllib.load(f)
    except (tomllib.TOMLDecodeError, OSError) as exc:
        print(f"{path}: {exc}")
        rc = 1

sys.exit(rc)
